#!/bin/bash
# tools/all-steps.sh: run every step of the lab in order on a running stack, one line a step: ok or FAILED.
# It rebuilds the data first (seed --reset, seed --reset-agent), so it can be repeated. About six minutes.
# With the scripted model the numbers at the end are fixed; with a real model only the wiring checks hold.
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
L="docker compose exec -T lab"
PJ="docker compose exec -T postgres psql -U postgres -d juniper -At"
PA="docker compose exec -T postgres psql -U postgres -d agent -At"
TOKEN="X-Service-Token: lab-token-not-a-secret"
LOG="$(mktemp)"; FAILED=0
step() {    # <name> <command>
  if bash -c "$2" > "$LOG" 2>&1 < /dev/null; then echo "ok      $1"; else echo "FAILED  $1"; tail -4 "$LOG" | sed 's/^/          /'; FAILED=1; fi
}
expect() {  # <name> <sql> <expected> [agent]: the fourth argument asks the agent's database instead of the business one
  local psql="$PJ"; [ "${4:-}" = agent ] && psql="$PA"
  local got; got="$($psql -c "$2" 2>&1 < /dev/null | tr '\n' ' ' | sed 's/ $//')"
  if [ "$got" = "$3" ]; then echo "ok      $1: $got"; else echo "FAILED  $1: got $got, expected $3"; FAILED=1; fi
}
requests() { echo "docker compose exec -T fake-model sh -c \"ls /logs/$1 2>/dev/null | grep -c request; true\""; }
COUNT_PAYMENTS='docker compose exec -T postgres psql -U postgres -d juniper -Atc "select count(*) from payments"'
kill_at_request() {  # <container> <request number> <log tag> <command in the lab image>: start it in its own container, kill it there
  docker rm -f "$1" > /dev/null 2>&1
  step "empty the request log $3" "$L python -m app.control $3"      # an old log would make the kill come at once
  step "start in its own container: $4" "docker compose run -d --name $1 lab $4"
  step "kill it with SIGKILL at request $2" "tools/kill-when.sh $1 $2 '$(requests "$3")'"
  docker rm -f "$1" > /dev/null 2>&1
  expect "payments made before it died" "select count(*) from payments" "18"
}
kill_at_payment() {  # <container> <docker run flags> <command>: kill it inside the payment tool, after its 8th row is written
  docker rm -f "$1" > /dev/null 2>&1
  step "start in its own container: $3" "docker compose run -d --name $1 $2 lab $3"
  step "kill it with SIGKILL inside the 8th payment" "tools/kill-when.sh $1 8 '$COUNT_PAYMENTS'"
  docker rm -f "$1" > /dev/null 2>&1
  expect "payment rows when it died" "select count(*) from payments" "8"
}
RESET="$L python -m seed.seed --reset-activity"
TWICE="select count(*), count(distinct invoice_number) from payments"
DONE="select (select count(*) from payments), (select count(*) from holds)"

echo "step 1: the data"
step "seed juniper and receiving" "$L python -m seed.seed --reset"
step "empty the agent database" "$L python -m seed.seed --reset-agent"
expect "invoices due 2026-11-27" "select count(*) from invoices where due_date = '2026-11-27'" "40"
echo "step 2: the agent by hand"
step "one call, no tools" "$L python agent_by_hand.py one"
step "tools on offer" "$L python agent_by_hand.py offer"
step "the loop" "$L python agent_by_hand.py loop"
echo "step 3: LangChain"
step "create_agent" "$L python agent_langchain.py && $L python agent_langchain.py graph"
step "the long job in one conversation" "$RESET && $L python agent_langchain.py run"
expect "payments and holds" "$DONE" "33|7"
echo "step 4: a deep agent"
step "bare" "$L python steps.py s4-bare"
step "a file in the state" "$L python steps.py s4-write"
step "a large tool result" "$L python steps.py s4-large"
step "files on a real folder" "$L python steps.py s4-disk"
echo "step 5: a kill, a list saved by hand, saved steps, a resume"
step "reset payments and holds" "$RESET"
kill_at_request payrun-nosave 114 s5-nosave-first "python steps.py s5-nosave first 300 helpers"
step "nothing was saved: started again, it starts over" "$L python steps.py s5-nosave again 0 helpers"
expect "payment rows and paid invoices: 18 were scheduled twice" "$TWICE" "51|33"
step "reset payments and holds" "$RESET"
kill_at_request payrun-hand 69 s2-saved-all-hand "python agent_by_hand_saved.py all-hand 300"
step "the list saved by hand: started again, it reads the list back" "$L python agent_by_hand_saved.py all-hand"
expect "payment rows and paid invoices" "$TWICE" "33|33"
step "PostgresSaver.setup()" "$L python steps.py s5-setup"
step "one saved thread" "$L python steps.py s5-one invoice-1042"
step "reset payments and holds" "$RESET"
kill_at_request payrun-friday-a 69 s5-friday-a "python steps.py s5-run friday-a 300"
step "resume friday-a" "$L python steps.py s5-run friday-a"
expect "payments and paid invoices after the resume" "$TWICE" "33|33"
step "reset payments and holds" "$RESET"
kill_at_payment payrun-friday-d "-e PAYMENT_CONFIRM_SECONDS=2" "python steps.py s5-run friday-d"
step "resume friday-d" "$L python steps.py s5-run friday-d"
expect "killed inside the tool: payment rows and paid invoices" "$TWICE" "34|33"
step "reset payments and holds" "$RESET"
kill_at_payment payrun-friday-e "-e PAYMENT_CONFIRM_SECONDS=2 -e PAYMENTS_IDEMPOTENT=1" "python steps.py s5-run friday-e"
step "resume friday-e" "docker compose exec -T -e PAYMENTS_IDEMPOTENT=1 lab python steps.py s5-run friday-e"
expect "the same kill with an idempotency key" "$TWICE" "33|33"
echo "step 6: approvals"
step "reset payments and holds" "$RESET"
step "pause, then approve" "$L python steps.py s6-ask dana-approve 1031 && $L python steps.py s6-decide dana-approve approve"
step "pause, then edit the amount" "$L python steps.py s6-ask dana-edit 1035 && $L python steps.py s6-decide dana-edit edit 3000.00"
step "pause, then reject" "$L python steps.py s6-ask dana-reject 1033 && $L python steps.py s6-decide dana-reject reject 'Not this week.'"
step "no checkpointer" "$L python steps.py s6-no-checkpointer 1036"
expect "payments after approve, edit and reject" "select invoice_number, amount_usd from payments order by 1" "1031|2655.00 1035|3000.00"
echo "step 7: memory"
step "PostgresStore.setup()" "$L python steps.py s7-setup"
step "run one, no memory yet" "$L python steps.py s7-ask friday-1 1034"
step "remember the freight rule" "$L python steps.py s7-remember friday-1"
step "run two, a new thread" "$L python steps.py s7-ask friday-2 1034"
step "another organization" "$L python steps.py s7-ask friday-3 1034 other-market"
step "the namespace from the docs" "$L python steps.py s7-server-info"
echo "step 8: a subagent"
step "reset payments and holds" "$RESET"
step "the run in one conversation" "$L python steps.py s8-direct direct-1"
expect "payments and holds" "$DONE" "33|7"
step "reset payments and holds" "$RESET"
step "the run delegated" "$L python steps.py s8-delegate delegate-1"
expect "payments and holds" "$DONE" "33|7"
step "reset payments and holds" "$RESET"
kill_at_request payrun-friday-k 114 s8-friday-k "python steps.py s8-delegate friday-k 300"
step "resume friday-k: killed inside a helper" "$L python steps.py s8-delegate friday-k"
expect "payments and paid invoices after the resume" "$TWICE" "33|33"
step "reset payments and holds" "$RESET"
step "delegated, with the memory file" "$L python steps.py s8-delegate-memory delegate-2"
expect "payments and holds" "$DONE" "36|4"
echo "step 9: the policy in a vector table"
step "the two URL forms" "$L python -m app.policy_index urls"
step "build the table" "$L python -m app.policy_index build"
step "search" "$L python -m app.policy_index search 'invoice without a purchase order'"
step "the agent uses search_policy" "$L python steps.py s9-ask 1063"
step "reset payments and holds" "$RESET"
step "the pause says who approves" "$L python steps.py s9-pay director-1039 1039 && $L python steps.py s9-decide director-1039 approve"
expect "payments marked for the store director" "select count(*) from payments where note like '%store director%'" "1"
echo "step 10: two agents"
step "the receiving agent over HTTP" "$L python -m tools.http POST http://receiving-agent:8000/ask '{\"question\": \"What arrived for purchase order PO-2207?\"}'"
step "one invoice across two agents" "$L python steps.py s10-ask 1055"
step "A2A: send and wait" "$L python -m tools.a2a_demo send PO-2220"
step "A2A: send, then check later" "$L python -m tools.a2a_demo later PO-2207"
step "one invoice across two agents, over A2A" "$L python steps.py s10-ask 1055 a2a"
step "two invoices, waiting for each answer" "$L python steps.py s10-two wait"
step "two invoices, both questions sent first" "$L python steps.py s10-two later"
step "reset payments and holds" "$RESET"
step "the payment run with every part on" "$L python steps.py s10-run final-1"
expect "payments, paid in dollars, holds" "select (select count(*) from payments), (select sum(amount_usd) from payments), (select count(*) from holds)" "36|159742.00|4"
echo "step 11: around the agent"
step "reset payments and holds" "$RESET"
step "a cap of 20 requests ends the run" "$L python steps.py s11-cap capped-1 20 | grep -q 'Model call limits exceeded'"
expect "payments and holds when the cap ended it" "$DONE" "8|1"
step "a permission refuses delete" "$L python steps.py s11-delete delete-1 protect | grep -q 'permission denied'"
step "the same permission refuses a new memory" "$L python steps.py s11-remember remember-1 protect | grep -q 'permission denied'"
expect "the memory row is still there" "select count(*) from store" "1" agent
step "reset payments and holds" "$RESET"
step "the service refuses a caller without its token" "$L python -m tools.http POST http://payables-agent:8000/runs '{\"thread_id\": \"all-steps\"}' | grep -q 'HTTP 401'"
step "the service starts the run" "$L python -m tools.http POST http://payables-agent:8000/runs '{\"thread_id\": \"all-steps\"}' '$TOKEN' | grep -q 'HTTP 202'"
step "every payment approved over HTTP" "$L python -m tools.dana all-steps --quiet"
expect "payments, paid in dollars, holds" "select (select count(*) from payments), (select sum(amount_usd) from payments), (select count(*) from holds)" "36|159742.00|4"
rm -f "$LOG"
[ "$FAILED" = 0 ] && echo "all steps ok" || { echo "some steps FAILED"; exit 1; }
